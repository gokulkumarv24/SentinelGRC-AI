import { Injectable } from '@nestjs/common';
import { AwsClient } from 'aws4fetch';
import { createReadStream } from 'node:fs';
import { mkdir, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, resolve, sep } from 'node:path';
import { Readable } from 'node:stream';
import { fileURLToPath } from 'node:url';
import { AppError } from '../../common/errors.js';
import { loadEnv } from '../../config/env.js';

/** Bounded retries and a per-request timeout, so a failing bucket surfaces as an error instead of a hung request. */
const S3_RETRIES = 2;
const S3_TIMEOUT_MS = 30_000;

/** Storage keys are generated by the server only: `<org uuid>/<category>/<uuid>`. */
const SAFE_KEY = /^[0-9a-f-]{36}\/[a-z_]{1,20}\/[0-9a-f-]{36}$/;

export interface StoredObject {
  stream: Readable;
  size: number;
}

export interface StorageAdapter {
  readonly kind: 'local' | 's3';
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<StoredObject>;
  delete(key: string): Promise<void>;
  /** Short-lived direct URL (S3 only); local storage streams through the authenticated API instead. */
  presignedUrl?(key: string, ttlSeconds: number, filename: string, disposition: 'inline' | 'attachment'): Promise<string>;
}

export function assertSafeKey(key: string): void {
  if (!SAFE_KEY.test(key)) throw new Error('Unsafe storage key');
}

/** The database points at an object that is not in storage (e.g. restored database, different bucket). */
function fileMissing(): AppError {
  return new AppError(404, 'file_not_found', 'The stored file could not be found. Upload or generate it again.');
}

/** Development storage under a directory outside any web root (spec §3.3). */
export class LocalStorage implements StorageAdapter {
  readonly kind = 'local' as const;
  private readonly root: string;

  constructor(path: string) {
    const repoRoot = fileURLToPath(new URL('../../../../../', import.meta.url));
    this.root = resolve(isAbsolute(path) ? path : resolve(repoRoot, path));
  }

  private pathFor(key: string): string {
    assertSafeKey(key);
    const full = resolve(this.root, key);
    if (!full.startsWith(this.root + sep)) throw new Error('Path traversal blocked');
    return full;
  }

  async put(key: string, body: Buffer): Promise<void> {
    const path = this.pathFor(key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, body, { flag: 'wx', mode: 0o600 });
  }

  async get(key: string): Promise<StoredObject> {
    const path = this.pathFor(key);
    const info = await stat(path).catch((e: NodeJS.ErrnoException) => {
      throw e.code === 'ENOENT' ? fileMissing() : e;
    });
    return { stream: createReadStream(path), size: info.size };
  }

  async delete(key: string): Promise<void> {
    await rm(this.pathFor(key), { force: true });
  }
}

/**
 * S3-compatible object storage (AWS S3, Cloudflare R2, Backblaze B2, MinIO). Credentials come from the
 * environment variables named by S3_ACCESS_KEY_ID_REF / S3_SECRET_ACCESS_KEY_REF.
 * The bucket must be private; downloads use presigned URLs with a short expiry.
 */
export class S3Storage implements StorageAdapter {
  readonly kind = 's3' as const;
  private readonly client: AwsClient;
  private readonly base: string;

  constructor(endpoint: string, bucket: string, region: string, accessKeyId: string, secretAccessKey: string) {
    this.client = new AwsClient({ accessKeyId, secretAccessKey, region, service: 's3', retries: S3_RETRIES });
    this.base = `${endpoint.replace(/\/$/, '')}/${encodeURIComponent(bucket)}`;
  }

  private url(key: string): string {
    assertSafeKey(key);
    return `${this.base}/${key}`;
  }

  private request(key: string, init: RequestInit = {}): Promise<Response> {
    return this.client.fetch(this.url(key), { ...init, signal: AbortSignal.timeout(S3_TIMEOUT_MS) });
  }

  /** Error with the provider's error code (e.g. AccessDenied) for the logs; never includes credentials. */
  private async failure(action: string, res: Response): Promise<Error> {
    const text = await res.text().catch(() => '');
    const code = /<Code>([^<]{1,80})<\/Code>/.exec(text)?.[1];
    return new Error(`Object storage ${action} failed (${res.status}${code ? ` ${code}` : ''})`);
  }

  async put(key: string, body: Buffer, contentType: string): Promise<void> {
    // No conditional (If-None-Match) write: not every S3-compatible provider supports it, and keys are
    // server-generated UUIDs, so an existing object is never overwritten in practice.
    const res = await this.request(key, { method: 'PUT', body: new Uint8Array(body), headers: { 'Content-Type': contentType } });
    if (!res.ok) throw await this.failure('upload', res);
  }

  async get(key: string): Promise<StoredObject> {
    const res = await this.request(key);
    if (res.status === 404) throw fileMissing();
    if (!res.ok || !res.body) throw await this.failure('read', res);
    return { stream: Readable.fromWeb(res.body as never), size: Number(res.headers.get('content-length') ?? 0) };
  }

  async delete(key: string): Promise<void> {
    const res = await this.request(key, { method: 'DELETE' });
    if (!res.ok && res.status !== 404) throw await this.failure('delete', res);
  }

  async presignedUrl(key: string, ttlSeconds: number, filename: string, disposition: 'inline' | 'attachment'): Promise<string> {
    const url = new URL(this.url(key));
    url.searchParams.set('X-Amz-Expires', String(ttlSeconds));
    url.searchParams.set('response-content-disposition', `${disposition}; filename="${filename.replace(/["\\]/g, '_')}"`);
    const signed = await this.client.sign(url.toString(), { method: 'GET', aws: { signQuery: true } });
    return signed.url;
  }
}

@Injectable()
export class StorageService {
  readonly adapter: StorageAdapter;

  constructor() {
    const env = loadEnv();
    if (env.STORAGE_BACKEND === 's3') {
      const keyId = process.env[process.env.S3_ACCESS_KEY_ID_REF ?? ''] ?? '';
      const secret = process.env[process.env.S3_SECRET_ACCESS_KEY_REF ?? ''] ?? '';
      if (!keyId || !secret) throw new Error('S3 credentials not found in the referenced environment variables');
      this.adapter = new S3Storage(env.S3_ENDPOINT!, env.S3_BUCKET!, env.S3_REGION ?? 'auto', keyId, secret);
    } else {
      this.adapter = new LocalStorage(env.LOCAL_STORAGE_PATH);
    }
  }
}
